import { occupancy, SIZE } from '../src/rules.js';

// Occupancy of the first three rows in the photographed cards. This coarse
// filter excludes a match without storing the pieces or solutions of the cards.
const prefixes = new Set(`
  110001/100101/111101 100111/100101/110111 000000/000000/011100 100100/100100/111100 110101/100111/111111 110100/110111/011111 011111/010111/011101 000111/001111/111111 011111/010111/110111 111011/111001/111001
  111100/100100/111100 111001/101001/111001 111110/001011/011111 111000/001011/111111 011110/111111/111111 111111/101111/111111 111100/101111/111000 111100/111100/111100 001110/001010/011110 100111/111100/111101
  111100/101100/111100 001111/101111/111100 001111/001111/001111 001110/011000/111110 111011/111001/111011 010111/110110/111111 111100/111100/111101 111100/001111/111000 111010/001010/111011 101111/101100/111100
  110111/000111/111101 111111/001100/111000 011011/011000/111000 100111/100101/110111 001111/001101/111101 111111/111101/111101 111011/111011/111011 100111/111100/111101 001111/001100/111101 111010/111011/111111
`.trim().split(/\s+/));
const fourTrucks = new Set(['111100/111100/111100', '011110/111111/111111']);

export function couldMatchReference(pieces, positions) {
  const grid = occupancy(pieces, positions);
  const prefix = [0, 1, 2].map(row =>
    grid.slice(row * SIZE, (row + 1) * SIZE).map(cell => Number(cell !== -1)).join('')
  ).join('/');
  if (!prefixes.has(prefix)) return false;
  return !fourTrucks.has(prefix) || pieces.filter(piece => piece.length === 3).length === 4;
}
